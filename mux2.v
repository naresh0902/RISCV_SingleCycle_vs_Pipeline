`timescale 1ns/1ps

//------------------------------------------------------------------------------
// 2-to-1 multiplexer (32-bit):  y = sel ? d1 : d0
//------------------------------------------------------------------------------
module mux2 (
    input  [31:0] d0, d1,
    input         sel,
    output [31:0] y
);
    assign y = sel ? d1 : d0;
endmodule
